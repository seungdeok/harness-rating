import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { parseDocument } from "yaml";
import type { Requirement, Rubric } from "../src/rubric/types.ts";
import { validateRubric } from "../src/rubric/validate.ts";

const input = "rubric/v0.1.yaml";

function text(value: string): string {
	return value
		.replaceAll("&", "&amp;")
		.replaceAll("<", "&lt;")
		.replaceAll(">", "&gt;")
		.replace(/[\\`*_[\]#|]/g, "\\$&")
		.replace(/\r?\n/g, " ");
}

function code(value: string): string {
	const runs = [...value.matchAll(/`+/g)].map((match) => match[0].length);
	const fence = "`".repeat(Math.max(0, ...runs) + 1);
	const padding = /^[` ]|[` ]$/.test(value) ? " " : "";
	return `${fence}${padding}${value}${padding}${fence}`;
}

function requirement(value: Requirement): string {
	if (typeof value === "string") {
		const anchor = value
			.toLowerCase()
			.replace(/[^\p{L}\p{N}_ -]/gu, "")
			.replaceAll(" ", "-");
		return `[${text(value)}](rubric.md#${encodeURIComponent(anchor)})`;
	}
	const children = "any_of" in value ? value.any_of : value.all_of;
	const operator = "any_of" in value ? " OR " : " AND ";
	return `(${children.map(requirement).join(operator)})`;
}

function header(title: string, rubric: Rubric): string[] {
	return [
		"<!-- Generated by scripts/gen-rubric-docs.ts. Do not edit by hand. -->",
		`# ${title}`,
		"",
		`Generated from [${input}](../${input}): rubric v${rubric.version}; sources version ${rubric.sources_version}.`,
		"",
		"Regenerate with `npm run generate:rubric-docs`; verify with `npm run check:rubric-docs`.",
		"",
	];
}

function checkDocs(rubric: Rubric): string {
	const lines = [
		...header("Rubric", rubric),
		"These are static configuration checks, not evidence of effectiveness. Detector identifiers and parameters below come directly from the rubric; see the [specification](spec/SPEC.md#level-checks) for detection rules and [levels](levels.md) for requirements.",
		"",
		"Evidence tiers count distinct organizations, not documents. A lower tier means less agreement, not less importance. Only explicit recommendations count; see the [source rules](spec/SPEC.md#source-rules).",
		"",
		"| Tier | Minimum organizations | Reference weight |",
		"| --- | --- | --- |",
		...Object.entries(rubric.evidence_tiers).map(
			([tier, values]) => `| ${tier} | ${values.min_orgs} | ${values.weight} |`,
		),
		"",
	];
	for (const check of rubric.checks) {
		lines.push(
			`## ${text(check.id)}`,
			"",
			`**What:** ${text(check.title)}`,
			"",
			`- **Dimension:** ${text(check.dimension)}`,
			`- **Evidence tier:** ${check.tier} (reference weight ${rubric.evidence_tiers[check.tier].weight})`,
			`- **Detection:** ${code(check.check)}`,
			`- **Parameters:** ${check.params === undefined ? "None." : code(JSON.stringify(check.params))}`,
			`- **Applies when:** ${check.applies_when === undefined ? "Always." : code(check.applies_when)}`,
			`- **Supported agents:** ${check.supported_by.map(code).join(", ")}`,
			`- **How to pass:** ${text(check.fix_hint)}`,
			"",
			"### Sources",
			"",
		);
		for (const source of check.sources) {
			// Angle-bracket destinations keep parentheses in source URLs intact.
			const url = source.url.replaceAll("<", "%3C").replaceAll(">", "%3E");
			lines.push(
				`- [${text(source.org)}](<${url}>) — checked ${source.checked}.`,
				`  Recommendation: ${text(source.recommendation)}`,
				"",
			);
		}
	}
	return lines.join("\n");
}

function levelDocs(rubric: Rubric): string {
	const levels = { L0: { requires: [] }, ...rubric.levels };
	return [
		...header("Levels", rubric),
		"**These levels are defined by this tool, not an industry standard.** They are a different axis from agent autonomy models.",
		"",
		"A level is reached when all of its required checks pass, together with those of every lower level. Each row adds requirements to the preceding levels. AND requires every operand; OR requires at least one. Parentheses preserve grouping.",
		"",
		"| Level | Additional required checks |",
		"| --- | --- |",
		...Object.entries(levels)
			.sort(([a], [b]) => a.localeCompare(b, "en"))
			.map(
				([level, value]) =>
					`| ${level} | ${value.requires.map(requirement).join(" AND ") || "None."} |`,
			),
		"",
		"The gate uses the level alone (`--min-level`); evidence tiers and reference weights do not change level requirements. See the [specification](spec/SPEC.md#levels) for level names, rationale, and the treatment of unsupported (capped) checks.",
		"",
	].join("\n");
}

try {
	const args = process.argv.slice(2);
	if (args.length > 1 || (args.length === 1 && args[0] !== "--check"))
		throw new Error("Usage: node scripts/gen-rubric-docs.ts [--check]");
	const document = parseDocument(readFileSync(input, "utf8"), {
		version: "1.2",
		uniqueKeys: true,
	});
	const problems = [...document.errors, ...document.warnings];
	if (problems.length > 0)
		throw new Error(problems.map((problem) => problem.message).join("\n"));
	const result = validateRubric(document.toJS({ maxAliasCount: 100 }));
	if (!result.valid) throw new Error(result.errors.join("\n"));
	const outputs = [
		["docs/rubric.md", checkDocs(result.rubric)],
		["docs/levels.md", levelDocs(result.rubric)],
	] as const;
	if (args[0] === "--check") {
		for (const [file, expected] of outputs) {
			let actual: string | undefined;
			try {
				actual = readFileSync(file, "utf8");
			} catch (error) {
				if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
			}
			if (actual !== expected) {
				console.error(`${file}: missing or stale generated documentation.`);
				process.exitCode = 1;
			}
		}
		if (process.exitCode === 1)
			console.error(
				"Fix: run npm run generate:rubric-docs and commit both docs.",
			);
		else console.log("Rubric documentation is up to date.");
	} else {
		mkdirSync("docs", { recursive: true });
		for (const [file, content] of outputs) {
			writeFileSync(file, content);
			console.log(`Generated ${file}`);
		}
	}
} catch (error) {
	console.error(
		`${input}: ${error instanceof Error ? error.message : String(error)}`,
	);
	process.exitCode = 1;
}
